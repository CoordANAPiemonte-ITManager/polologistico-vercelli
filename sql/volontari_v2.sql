create or replace function public.vol_data_sicura(p text)
returns date language plpgsql stable set search_path = public as $$
declare d date;
begin
  if p is null or btrim(p) = '' then return null; end if;
  if btrim(p) !~ '^\d{4}-\d{2}-\d{2}$' then raise exception 'DATA_NON_VALIDA'; end if;
  begin
    d := btrim(p)::date;
  exception when others then
    raise exception 'DATA_NON_VALIDA';
  end;
  if d < date '1950-01-01' or d > current_date then raise exception 'DATA_NON_VALIDA'; end if;
  return d;
end;
$$;

create or replace function public.vol_chiudi_se_finita(p_richiesta bigint)
returns void language sql security definer set search_path = public as $$
  update vol_richieste_sezione set stato = 'CHIUSA', chiusa_at = now()
  where id = p_richiesta and stato = 'INVIATA'
    and not exists (select 1 from vol_proposte where richiesta_id = p_richiesta and stato = 'IN_ATTESA');
$$;

-- Crea le proposte da quanto inviato dalla Sezione (link o Excel). Interna.
-- p_righe: [{volontario_id, note, requisiti:[{requisito_id, data_base, data_agg}]}]
-- p_segn:  [{testo}]
-- Diventano proposte solo le date diverse da quelle in archivio.
create or replace function public.vol_crea_proposte(p_richiesta bigint, p_righe jsonb, p_segn jsonb, p_nome text, p_ruolo text)
returns int language plpgsql security definer set search_path = public as $$
declare
  ric vol_richieste_sezione%rowtype;
  riga jsonb; rq jsonb; sg jsonb;
  v_vid uuid; v_rid bigint; v_db date; v_da date; v_cb date; v_ca date; v_prev boolean;
  v_note text; v_testo text;
  n int := 0; n_vol int;
begin
  select * into ric from vol_richieste_sezione where id = p_richiesta for update;
  if not found then raise exception 'RICHIESTA_NON_TROVATA'; end if;
  if ric.stato <> 'APERTA' then raise exception 'RICHIESTA_NON_APERTA'; end if;
  if ric.scadenza < now() then raise exception 'RICHIESTA_SCADUTA'; end if;
  if nullif(btrim(coalesce(p_nome, '')), '') is null then raise exception 'NOME_MANCANTE'; end if;
  if jsonb_typeof(coalesce(p_righe, '[]'::jsonb)) <> 'array' or jsonb_array_length(coalesce(p_righe, '[]'::jsonb)) > 1500
     or jsonb_typeof(coalesce(p_segn, '[]'::jsonb)) <> 'array' or jsonb_array_length(coalesce(p_segn, '[]'::jsonb)) > 200 then
    raise exception 'DATI_NON_VALIDI';
  end if;

  for riga in select * from jsonb_array_elements(coalesce(p_righe, '[]'::jsonb)) loop
    begin
      v_vid := (riga->>'volontario_id')::uuid;
    exception when others then
      raise exception 'VOLONTARIO_NON_VALIDO';
    end;
    if not exists (select 1 from vol_volontari where id = v_vid and sezione = ric.sezione and stato = 'ATTIVO') then
      raise exception 'VOLONTARIO_NON_VALIDO';
    end if;
    v_note := nullif(left(btrim(coalesce(riga->>'note', '')), 500), '');
    n_vol := 0;

    for rq in select * from jsonb_array_elements(coalesce(riga->'requisiti', '[]'::jsonb)) loop
      begin
        v_rid := (rq->>'requisito_id')::bigint;
      exception when others then
        raise exception 'REQUISITO_NON_VALIDO';
      end;
      if v_rid is null or not (v_rid = any(ric.requisiti_inclusi)) then raise exception 'REQUISITO_NON_VALIDO'; end if;
      v_db := vol_data_sicura(rq->>'data_base');
      v_da := vol_data_sicura(rq->>'data_agg');
      select prevede_aggiornamento into v_prev from vol_requisiti where id = v_rid;
      v_cb := null; v_ca := null;
      select s.data_base, s.ultimo_aggiornamento into v_cb, v_ca
        from vol_stato_calcola(v_vid, null) s where s.requisito_id = v_rid;

      if v_db is not null and v_db is distinct from v_cb then
        insert into vol_proposte (richiesta_id, volontario_id, requisito_id, tipo_evento, data, valore_attuale, note)
        values (ric.id, v_vid, v_rid, 'BASE', v_db, v_cb, v_note);
        n := n + 1; n_vol := n_vol + 1;
      end if;
      if v_da is not null and v_prev and v_da is distinct from v_ca then
        insert into vol_proposte (richiesta_id, volontario_id, requisito_id, tipo_evento, data, valore_attuale, note)
        values (ric.id, v_vid, v_rid, 'AGGIORNAMENTO', v_da, v_ca, v_note);
        n := n + 1; n_vol := n_vol + 1;
      end if;
    end loop;

    -- nota senza date nuove: diventa una segnalazione su quel volontario
    if v_note is not null and n_vol = 0 then
      insert into vol_proposte (richiesta_id, volontario_id, tipo_proposta, note)
      values (ric.id, v_vid, 'SEGNALAZIONE', v_note);
      n := n + 1;
    end if;
  end loop;

  for sg in select * from jsonb_array_elements(coalesce(p_segn, '[]'::jsonb)) loop
    v_testo := nullif(left(btrim(coalesce(sg->>'testo', '')), 500), '');
    if v_testo is not null then
      insert into vol_proposte (richiesta_id, tipo_proposta, note) values (ric.id, 'SEGNALAZIONE', v_testo);
      n := n + 1;
    end if;
  end loop;

  update vol_richieste_sezione set
    stato = case when n = 0 then 'CHIUSA' else 'INVIATA' end,
    chiusa_at = case when n = 0 then now() end,
    inviata_at = now(),
    compilatore_nome = left(btrim(p_nome), 100),
    compilatore_ruolo = left(nullif(btrim(coalesce(p_ruolo, '')), ''), 100)
  where id = ric.id;
  return n;
end;
$$;

-- ---------- per l'app (gestore) ----------
create or replace function public.vol_richiesta_crea(p_sezione text, p_requisiti bigint[], p_canale text,
                                                     p_giorni int default 30, p_note text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_id bigint; v_token text;
begin
  if not vol_gestore() then raise exception 'Permesso negato'; end if;
  if not exists (select 1 from vol_sezioni where sezione = p_sezione) then raise exception 'Sezione sconosciuta'; end if;
  if p_canale not in ('LINK','EXCEL') then raise exception 'Canale non valido'; end if;
  if p_requisiti is null or cardinality(p_requisiti) = 0 then raise exception 'Scegli almeno un corso o abilitazione'; end if;
  if exists (select 1 from unnest(p_requisiti) x where not exists (select 1 from vol_requisiti r where r.id = x and r.attivo)) then
    raise exception 'Corso o abilitazione non valido';
  end if;
  if p_giorni is null or p_giorni < 1 or p_giorni > 180 then raise exception 'Scadenza non valida (da 1 a 180 giorni)'; end if;
  if p_canale = 'LINK' then v_token := encode(extensions.gen_random_bytes(32), 'hex'); end if;
  insert into vol_richieste_sezione (sezione, requisiti_inclusi, canale, token, scadenza, note_master, creata_da)
  values (p_sezione, (select array_agg(distinct x) from unnest(p_requisiti) x), p_canale, v_token,
          now() + make_interval(days => p_giorni), nullif(left(btrim(coalesce(p_note, '')), 1000), ''), auth.uid())
  returning id into v_id;
  return jsonb_build_object('id', v_id, 'token', v_token);
end;
$$;

-- token e mail PC della Sezione (per "Copia link" e "Invia mail")
create or replace function public.vol_richiesta_link(p_id bigint)
returns table (token text, email_pc text) language sql stable security definer set search_path = public as $$
  select r.token, z.email_pc
  from vol_richieste_sezione r
  left join sezioni_ana z on regexp_replace(upper(z.nome), '[^A-Z]', '', 'g') = regexp_replace(upper(r.sezione), '[^A-Z]', '', 'g')
  where r.id = p_id and r.canale = 'LINK' and vol_gestore();
$$;

-- REVOCA / PROROGA (giorni) / CHIUDI
create or replace function public.vol_richiesta_azione(p_id bigint, p_azione text, p_giorni int default null)
returns void language plpgsql security definer set search_path = public as $$
declare ric vol_richieste_sezione%rowtype;
begin
  if not vol_gestore() then raise exception 'Permesso negato'; end if;
  select * into ric from vol_richieste_sezione where id = p_id for update;
  if not found then raise exception 'Richiesta non trovata'; end if;
  if p_azione = 'REVOCA' then
    if ric.stato <> 'APERTA' then raise exception 'Si può revocare solo una richiesta aperta'; end if;
    update vol_richieste_sezione set stato = 'REVOCATA', chiusa_at = now() where id = p_id;
  elsif p_azione = 'PROROGA' then
    if ric.stato <> 'APERTA' then raise exception 'Si può prorogare solo una richiesta aperta'; end if;
    if p_giorni is null or p_giorni < 1 or p_giorni > 180 then raise exception 'Giorni non validi (da 1 a 180)'; end if;
    update vol_richieste_sezione set scadenza = greatest(scadenza, now()) + make_interval(days => p_giorni) where id = p_id;
  elsif p_azione = 'CHIUDI' then
    if ric.stato <> 'INVIATA' then raise exception 'Si può chiudere solo una richiesta inviata'; end if;
    if exists (select 1 from vol_proposte where richiesta_id = p_id and stato = 'IN_ATTESA') then
      raise exception 'Ci sono ancora proposte da validare';
    end if;
    update vol_richieste_sezione set stato = 'CHIUSA', chiusa_at = now() where id = p_id;
  else
    raise exception 'Azione non valida';
  end if;
end;
$$;

-- Excel compilato caricato dal master
create or replace function public.vol_richiesta_carica(p_id bigint, p_righe jsonb, p_segn jsonb, p_nome text, p_ruolo text)
returns int language plpgsql security definer set search_path = public as $$
begin
  if not vol_gestore() then raise exception 'Permesso negato'; end if;
  if not exists (select 1 from vol_richieste_sezione where id = p_id and canale = 'EXCEL') then
    raise exception 'Richiesta Excel non trovata';
  end if;
  update vol_richieste_sezione
     set bozza = jsonb_build_object('righe', coalesce(p_righe, '[]'::jsonb), 'segnalazioni', coalesce(p_segn, '[]'::jsonb)),
         bozza_at = now()
   where id = p_id and stato = 'APERTA';
  return vol_crea_proposte(p_id, p_righe, p_segn, p_nome, p_ruolo);
end;
$$;

-- APPROVA (solo eventi) / RIFIUTA (con motivo) / GESTITA (solo segnalazioni)
create or replace function public.vol_valida_proposta(p_id bigint, p_esito text, p_nota text default null)
returns void language plpgsql security definer set search_path = public as $$
declare
  p vol_proposte%rowtype; v_canale text; v_ev bigint;
begin
  if not vol_gestore() then raise exception 'Permesso negato'; end if;
  select * into p from vol_proposte where id = p_id for update;
  if not found then raise exception 'Proposta non trovata'; end if;
  if p.stato <> 'IN_ATTESA' then raise exception 'Proposta già validata'; end if;
  select canale into v_canale from vol_richieste_sezione where id = p.richiesta_id;

  if p_esito = 'APPROVA' then
    if p.tipo_proposta <> 'EVENTO' then raise exception 'Le segnalazioni si segnano come gestite'; end if;
    insert into vol_eventi_requisito (volontario_id, requisito_id, tipo, data, origine, note, approvato_da, proposta_id)
    values (p.volontario_id, p.requisito_id, p.tipo_evento, p.data,
            case v_canale when 'LINK' then 'SEZIONE_LINK' else 'SEZIONE_EXCEL' end,
            p.note, auth.uid(), p.id)
    returning id into v_ev;
    update vol_proposte set stato = 'APPROVATA', validata_da = auth.uid(), validata_at = now(), evento_id = v_ev,
           nota_master = nullif(left(btrim(coalesce(p_nota, '')), 500), '')
     where id = p_id;
  elsif p_esito = 'RIFIUTA' then
    if nullif(btrim(coalesce(p_nota, '')), '') is null then raise exception 'Indica il motivo del rifiuto'; end if;
    update vol_proposte set stato = 'RIFIUTATA', validata_da = auth.uid(), validata_at = now(),
           motivo_rifiuto = left(btrim(p_nota), 500)
     where id = p_id;
  elsif p_esito = 'GESTITA' then
    if p.tipo_proposta <> 'SEGNALAZIONE' then raise exception 'Solo le segnalazioni si segnano come gestite'; end if;
    update vol_proposte set stato = 'GESTITA', validata_da = auth.uid(), validata_at = now(),
           nota_master = nullif(left(btrim(coalesce(p_nota, '')), 500), '')
     where id = p_id;
  else
    raise exception 'Esito non valido';
  end if;
  perform vol_chiudi_se_finita(p.richiesta_id);
end;
$$;

-- Approva tutte le proposte di evento ancora in attesa di una richiesta
create or replace function public.vol_approva_tutte(p_richiesta bigint)
returns int language plpgsql security definer set search_path = public as $$
declare x record; n int := 0;
begin
  if not vol_gestore() then raise exception 'Permesso negato'; end if;
  for x in select id from vol_proposte
           where richiesta_id = p_richiesta and stato = 'IN_ATTESA' and tipo_proposta = 'EVENTO' order by id loop
    perform vol_valida_proposta(x.id, 'APPROVA', null);
    n := n + 1;
  end loop;
  return n;
end;
$$;

-- ---------- per la Edge Function vol-pub (solo service_role) ----------
create or replace function public.vol_pub_limite(p_chiave text, p_max int default 120, p_minuti int default 10)
returns boolean language plpgsql security definer set search_path = public as $$
declare n int;
begin
  delete from vol_pub_accessi where at < now() - interval '2 days';
  insert into vol_pub_accessi (chiave) values (left(p_chiave, 128));
  select count(*) into n from vol_pub_accessi where chiave = left(p_chiave, 128) and at > now() - make_interval(mins => p_minuti);
  return n <= p_max;
end;
$$;

create or replace function public.vol_pub_trova(p_token text)
returns vol_richieste_sezione language plpgsql stable security definer set search_path = public as $$
declare ric vol_richieste_sezione%rowtype;
begin
  if p_token is null or p_token !~ '^[0-9a-f]{64}$' then raise exception 'TOKEN_NON_VALIDO'; end if;
  select * into ric from vol_richieste_sezione where token = p_token and canale = 'LINK';
  if not found then raise exception 'TOKEN_NON_VALIDO'; end if;
  if ric.stato = 'REVOCATA' then raise exception 'RICHIESTA_REVOCATA'; end if;
  return ric;
end;
$$;

create or replace function public.vol_pub_apri(p_token text)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare ric vol_richieste_sezione%rowtype;
begin
  ric := vol_pub_trova(p_token);
  if ric.stato = 'APERTA' and ric.scadenza < now() then raise exception 'RICHIESTA_SCADUTA'; end if;
  return jsonb_build_object(
    'sezione', ric.sezione,
    'note', ric.note_master,
    'scadenza', ric.scadenza,
    'stato', ric.stato,
    'modificabile', ric.stato = 'APERTA',
    'compilatore_nome', ric.compilatore_nome,
    'compilatore_ruolo', ric.compilatore_ruolo,
    'inviata_at', ric.inviata_at,
    'bozza', ric.bozza,
    'bozza_at', ric.bozza_at,
    'requisiti', coalesce((
      select jsonb_agg(jsonb_build_object('id', r.id, 'nome', r.nome, 'tipo', r.tipo, 'aggiornamento', r.prevede_aggiornamento)
                       order by r.ordine, r.id)
      from vol_requisiti r where r.id = any(ric.requisiti_inclusi)), '[]'::jsonb),
    'volontari', coalesce((
      select jsonb_agg(jsonb_build_object('id', v.id, 'cognome', v.cognome, 'nome', v.nome, 'gruppo', v.gruppo,
                                          'eta', case when v.data_nascita is not null then date_part('year', age(v.data_nascita))::int end,
                                          'cf4', right(v.cf, 4))
                       order by v.cognome, v.nome)
      from vol_volontari v where v.sezione = ric.sezione and v.stato = 'ATTIVO'), '[]'::jsonb),
    'stato_attuale', coalesce((
      select jsonb_agg(jsonb_build_object('v', s.volontario_id, 'r', s.requisito_id, 'stato', s.stato,
                                          'base', s.data_base, 'agg', s.ultimo_aggiornamento, 'scad', s.data_scadenza))
      from vol_stato_calcola(null, ric.sezione) s
      join vol_volontari v on v.id = s.volontario_id and v.stato = 'ATTIVO'
      where s.requisito_id = any(ric.requisiti_inclusi)), '[]'::jsonb)
  );
end;
$$;

create or replace function public.vol_pub_salva(p_token text, p_bozza jsonb)
returns timestamptz language plpgsql security definer set search_path = public as $$
declare ric vol_richieste_sezione%rowtype; v_at timestamptz := now();
begin
  ric := vol_pub_trova(p_token);
  if ric.stato <> 'APERTA' then raise exception 'RICHIESTA_NON_APERTA'; end if;
  if ric.scadenza < now() then raise exception 'RICHIESTA_SCADUTA'; end if;
  if p_bozza is null or jsonb_typeof(p_bozza) <> 'object' or pg_column_size(p_bozza) > 400000 then
    raise exception 'DATI_NON_VALIDI';
  end if;
  update vol_richieste_sezione set bozza = p_bozza, bozza_at = v_at where id = ric.id;
  return v_at;
end;
$$;

create or replace function public.vol_pub_invia(p_token text, p_bozza jsonb, p_nome text, p_ruolo text)
returns int language plpgsql security definer set search_path = public as $$
declare ric vol_richieste_sezione%rowtype;
begin
  ric := vol_pub_trova(p_token);
  if p_bozza is null or jsonb_typeof(p_bozza) <> 'object' or pg_column_size(p_bozza) > 400000 then
    raise exception 'DATI_NON_VALIDI';
  end if;
  update vol_richieste_sezione set bozza = p_bozza, bozza_at = now() where id = ric.id and stato = 'APERTA';
  return vol_crea_proposte(ric.id, p_bozza->'righe', p_bozza->'segnalazioni', p_nome, p_ruolo);
end;
$$;

