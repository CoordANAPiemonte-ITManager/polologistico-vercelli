-- SF02 / SF03: aggiornamento previsto, collegati a SF02A / SF03A (i nomi esistenti restano).
-- Se il requisito non esiste lo crea. Le validità si inseriscono dal menu.
do $$
declare
  c record;
begin
  for c in select * from (values ('SF02','SF02A','Corso 12 ore'), ('SF03','SF03A','Corso Capisquadra')) as t(base, agg, nome) loop
    if exists (select 1 from public.vol_requisiti r join public.catalogo_corsi k on k.id = r.corso_formazione_id where k.codice = c.base) then
      update public.vol_requisiti r set
        prevede_aggiornamento = true,
        corso_aggiornamento_id = coalesce(r.corso_aggiornamento_id, (select id from public.catalogo_corsi where codice = c.agg))
      where r.corso_formazione_id = (select id from public.catalogo_corsi where codice = c.base);
    else
      insert into public.vol_requisiti (nome, tipo, prevede_aggiornamento, corso_formazione_id, corso_aggiornamento_id, ordine)
      select c.nome, 'CORSO', true,
             (select id from public.catalogo_corsi where codice = c.base),
             (select id from public.catalogo_corsi where codice = c.agg),
             coalesce((select max(ordine) from public.vol_requisiti), 0) + 1
      on conflict do nothing;
    end if;
  end loop;
end $$;

