create function public.vol_eventi_calcola(p_volontario uuid default null, p_sezione text default null)
returns table (
  evento_id bigint, volontario_id uuid, requisito_id bigint, tipo text, data date, origine text,
  documento_path text, edizione text, note text, creato_da text, created_at timestamptz,
  approvato_da text, annullato boolean, motivo_annullamento text
)
language sql stable security definer set search_path = public as $$
  select e.id, e.volontario_id, e.requisito_id, e.tipo, e.data, e.origine,
         null::text, null::text, e.note, uc.nome, e.created_at, ua.nome,
         e.annullato_at is not null, e.motivo_annullamento
  from vol_eventi_requisito e
  join vol_volontari v on v.id = e.volontario_id
  left join app_users uc on uc.id = e.created_by
  left join app_users ua on ua.id = e.approvato_da
  where (p_volontario is null or e.volontario_id = p_volontario)
    and (p_sezione is null or v.sezione = p_sezione)
  union all
  -- eventi automatici dagli attestati della Scuola di Formazione
  select null::bigint, v.id, r.id,
         case when ed.catalogo_corso_id = r.corso_formazione_id then 'BASE' else 'AGGIORNAMENTO' end,
         coalesce(i.data_completamento, ed.data_corso), 'SCUOLA',
         d.storage_path, ed.label, null::text, null::text, null::timestamptz, null::text, false, null::text
  from vol_requisiti r
  join edizioni_corso ed       on ed.catalogo_corso_id = r.corso_formazione_id
                               or ed.catalogo_corso_id = r.corso_aggiornamento_id
  join iscrizioni_corsi i      on i.edizione_corso_id = ed.id
  join volontari_formazione vf on vf.id = i.volontario_id
  join vol_volontari v         on v.cf = upper(btrim(vf.codice_fiscale))
  left join lateral (
    select dv.storage_path from documenti_volontario dv
    where dv.iscrizione_id = i.id and dv.tipo = 'attestato'
    order by dv.id desc limit 1
  ) d on true
  where (d.storage_path is not null or i.attestato_rilasciato)
    and (p_volontario is null or v.id = p_volontario)
    and (p_sezione is null or v.sezione = p_sezione);
$$;

create function public.vol_stato_calcola(p_volontario uuid default null, p_sezione text default null)
returns table (
  volontario_id uuid, requisito_id bigint,
  data_base date, ultimo_aggiornamento date,
  data date,              -- riferimento: la più recente tra base e aggiornamento
  data_scadenza date,
  origine text,           -- origine dell'evento di riferimento
  origine_base text, origine_aggiornamento text,
  stato text,
  documento_path text, edizione text
)
language sql stable security definer set search_path = public as $$
  with ev as (
    select * from vol_eventi_calcola(p_volontario, p_sezione) where not annullato
  ),
  b as (
    select distinct on (ev.volontario_id, ev.requisito_id) ev.*
    from ev where ev.tipo = 'BASE'
    order by ev.volontario_id, ev.requisito_id, ev.data desc nulls last, (ev.origine = 'SCUOLA') desc
  ),
  a as (
    select distinct on (ev.volontario_id, ev.requisito_id) ev.*
    from ev where ev.tipo = 'AGGIORNAMENTO'
    order by ev.volontario_id, ev.requisito_id, ev.data desc nulls last, (ev.origine = 'SCUOLA') desc
  ),
  k as (
    select b.volontario_id, b.requisito_id from b
    union
    select a.volontario_id, a.requisito_id from a
  ),
  c as (
    select k.volontario_id, k.requisito_id,
           b.volontario_id is not null as ha_base,
           b.data as data_base, a.data as data_agg,
           b.origine as origine_base, a.origine as origine_agg,
           b.documento_path as doc_base, b.edizione as ed_base,
           a.documento_path as doc_agg, a.edizione as ed_agg,
           (a.data is not null and (b.data is null or a.data > b.data)) as ultimo_agg,
           r.validita_mesi, r.validita_aggiornamento_mesi, r.prevede_aggiornamento, r.preavviso_giorni
    from k
    join vol_requisiti r on r.id = k.requisito_id
    left join b on b.volontario_id = k.volontario_id and b.requisito_id = k.requisito_id
    left join a on a.volontario_id = k.volontario_id and a.requisito_id = k.requisito_id
  ),
  s as (
    select c.*,
           greatest(c.data_base, c.data_agg) as rif,
           case when c.ultimo_agg then coalesce(c.validita_aggiornamento_mesi, c.validita_mesi) else c.validita_mesi end as mesi
    from c
  ),
  t as (
    select s.*,
           case when s.mesi is not null and s.rif is not null
                then (s.rif + make_interval(months => s.mesi))::date end as scad
    from s
  )
  select t.volontario_id, t.requisito_id, t.data_base, t.data_agg, t.rif, t.scad,
         case when t.ultimo_agg then t.origine_agg else t.origine_base end,
         t.origine_base, t.origine_agg,
         case
           when not t.ha_base then 'ANOMALIA'
           when t.scad is null then 'VALIDO'
           when t.scad < current_date then case when t.prevede_aggiornamento then 'DA_AGGIORNARE' else 'SCADUTO' end
           when t.scad - t.preavviso_giorni <= current_date then 'IN_SCADENZA'
           else 'VALIDO'
         end,
         case when t.ultimo_agg then t.doc_agg else t.doc_base end,
         case when t.ultimo_agg then t.ed_agg else t.ed_base end
  from t;
$$;

