-- Annullare un evento (manuale o da Sezione); quelli della Scuola non si toccano
create or replace function public.vol_annulla_evento(p_id bigint, p_motivo text)
returns void language plpgsql security definer set search_path = public as $$
declare
  e vol_eventi_requisito%rowtype;
begin
  select * into e from vol_eventi_requisito where id = p_id for update;
  if not found then raise exception 'Evento non trovato'; end if;
  if not vol_permesso_sezione((select sezione from vol_volontari where id = e.volontario_id), true) then
    raise exception 'Permesso negato';
  end if;
  if e.annullato_at is not null then raise exception 'Evento già annullato'; end if;
  if nullif(btrim(p_motivo), '') is null then raise exception 'Indica il motivo dell''annullamento'; end if;
  update vol_eventi_requisito
     set annullato_at = now(), annullato_da = auth.uid(), motivo_annullamento = left(btrim(p_motivo), 500)
   where id = p_id;
end;
$$;

